class ScriptGenerator {
  constructor(distro, programs) {
    this.distro = distro;
    this.programs = programs;
    this.privilege_escalation_command = "sudo"; // TODO: make this configurable in a later version
  }

  _retrievePackageNames() {
    const packageNames = [];
    const customSlugs = [];

    for (const program of this.programs) {
      const names = program.package_names || {};
      const packageName = names[this.distro.slug] || names["default"];
      if (packageName === "CUSTOM_INSTALL") {
        customSlugs.push(program.slug);
      } else if (packageName) {
        packageNames.push(packageName);
      }
    }

    return { packageNames, customSlugs };
  }

  _buildPackageInstallCmd(packageNames) {
    return `${this.privilege_escalation_command} ${this.distro.install_package_command} ${packageNames.join(" ")}`;
  }

  async _get_custom_install(slug) {
    const program = this.programs.find(p => p.slug === slug);
    const customScript = await fetch(`/programs/${slug}/custom_install/install.sh`).then(r => r.text());
    if (program?.dependencies?.length) {
      const packageInstallCmd = this._buildPackageInstallCmd(program.dependencies);
      return packageInstallCmd + "\n" + customScript;
    }
    return customScript;
  }

  async _custom_installs(customSlugs) {
    const scripts = await Promise.all(customSlugs.map(slug => this._get_custom_install(slug)));
    return scripts.join("\n");
  }

  _script_header() {
    const date = new Date().toISOString().split("T")[0];
    return [
      "#!/bin/bash",
      `# Script for ${this.distro.name}`,
      "# Generated by Linux Setup Generator",
      "",
    ].join("\n");
  }

  async _buildScript() {
    const { packageNames, customSlugs } = this._retrievePackageNames();
    const installCmd = this._buildPackageInstallCmd(packageNames);
    const customCmd = await this._custom_installs(customSlugs);
    return this._script_header() + installCmd + "\n" + customCmd + "\n";
  }

  async get_script() {
    await new Promise(resolve => setTimeout(resolve, 3000));
    return this._buildScript();
  }
}
